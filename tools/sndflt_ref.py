#!/usr/bin/env python3
"""sndflt_ref.py <out.flt> | --design | --sv: the Enhanced sound's output stage (rtl/rabbit_sndflt.sv) in integer arithmetic, bit for bit.

The EQ, fitted against a recording of a real board (the attract mode, 95 s; docs/hardware.md "Sound"), RBJ cookbook biquads at the
chip's rate (40 MHz / 834 = 47,962 Hz):
  three 2-pole Butterworth high-passes at 175 Hz (the decoder's wander and rumble, which the board does not have)
  peaking +3.0 dB at 220 Hz (Q 1.0), +0.8 dB at 2 kHz (Q 1.4), -3.5 dB at 4.6 kHz (Q 1.0), +3.8 dB at 8.5 kHz (Q 1.4)
  a 2-pole Butterworth low-pass at 12.5 kHz, with +1.5 dB of make-up gain (the stages take about that much loudness away: Enhanced
  then plays as loud as MAME's sound, EBU R128, with the peaks still 7 dB under full scale)
Fixed point: the signal with 8 fraction bits in 27 bits, coefficients Q2.25, a 57-bit sum rounded back (direct form I, the sections
sharing their histories).

<out.flt>: what the sound bench recorded (sim/run_snd.sh with ENH=1: per chip sample the mix, int32 left and right, and the stage's
output for the sample before), run through the model and compared with the recorded output.
--design: the coefficients; --sv: the coefficient function for the RTL."""
import math, struct, sys

FS = 40e6 / 834
FB = 25
GAIN_DB = 1.5
SECTIONS = [('hp', 175, 0), ('hp', 175, 0), ('hp', 175, 0),
            ('peak', 220, 3.0, 1.0), ('peak', 2000, 0.8, 1.4), ('peak', 4600, -3.5, 1.0), ('peak', 8500, 3.8, 1.4),
            ('lp', 12500, 0)]


def biquad(sec):
    kind, f0 = sec[0], sec[1]
    w = 2 * math.pi * f0 / FS; c = math.cos(w); s = math.sin(w)
    if kind == 'peak':
        A = 10 ** (sec[2] / 40); al = s / (2 * sec[3])
        b = [1 + al * A, -2 * c, 1 - al * A]; a0 = 1 + al / A; a = [-2 * c, 1 - al / A]
    else:
        al = s / (2 / math.sqrt(2))
        b = [(1 + c) / 2, -(1 + c), (1 + c) / 2] if kind == 'hp' else [(1 - c) / 2, 1 - c, (1 - c) / 2]
        a0 = 1 + al; a = [-2 * c, 1 - al]
    return [v / a0 for v in b], [v / a0 for v in a]


def design():
    out = []
    for sec in SECTIONS:
        b, a = biquad(sec)
        if sec[0] == 'lp': b = [v * 10 ** (GAIN_DB / 20) for v in b]
        q = [round(v * 2 ** FB) for v in b + a]
        if sec[0] == 'hp': q[1] = -2 * q[0]                   # exactly no DC
        if sec[0] == 'lp': q[1] = 2 * q[0]                    # unity at DC
        out.append((q[0], q[1], q[2], -q[3], -q[4]))          # b0, b1, b2, -a1, -a2
    return out


C = design()
SAT27 = (1 << 26) - 1


def run(xs):
    """xs: one side's mix samples; returns the 16-bit outputs"""
    n = len(C)
    h = [[0, 0] for _ in range(n + 1)]
    ys = []
    for x in xs:
        cur = x << 8
        yk = []
        for k in range(n):
            b0, b1, b2, na1, na2 = C[k]
            acc = b0 * cur + b1 * h[k][0] + b2 * h[k][1] + na1 * h[k + 1][0] + na2 * h[k + 1][1]
            y = max(-SAT27 - 1, min(SAT27, (acc + (1 << (FB - 1))) >> FB))
            yk.append(y); cur = y
        h[0] = [x << 8, h[0][0]]
        for lv in range(1, n + 1): h[lv] = [yk[lv - 1], h[lv][0]]
        ys.append(max(-32768, min(32767, yk[-1] >> 8)))
    return ys


def sv():
    lines = ['    // generated by tools/sndflt_ref.py --sv: b0, b1, b2, -a1, -a2 of each section, Q2.%d' % FB,
             '    function automatic logic signed [26:0] coef(input logic [3:0] k, input logic [2:0] m);',
             '        case ({k, m})']
    for k, c in enumerate(C):
        for m, v in enumerate(c):
            lines.append("            {4'd%d, 3'd%d}: return %s27'sd%d;" % (k, m, '-' if v < 0 else '', abs(v)))
    lines += ["            default: return 27'sd0;", '        endcase', '    endfunction']
    return '\n'.join(lines)


if __name__ == '__main__':
    if '--design' in sys.argv:
        for sec, c in zip(SECTIONS, C): print(sec, '-> b0 b1 b2 -a1 -a2 =', c)
        sys.exit(0)
    if '--sv' in sys.argv:
        print(sv()); sys.exit(0)
    d = open(sys.argv[1], 'rb').read()
    rec = struct.unpack('<%di' % (len(d) // 4), d)
    ml, mr, fl, fr = rec[0::4], rec[1::4], rec[2::4], rec[3::4]
    bad = 0
    for side, xs, got in (('left', ml, fl), ('right', mr, fr)):
        ys = run(xs)
        n = len(xs) - 1                                        # the output at sample n + 1 is the stage's result for sample n
        diff = [i for i in range(n) if ys[i] != got[i + 1]]
        print('%s: %d samples, %d differ%s' % (side, n, len(diff), (' (first at %d: model %d, RTL %d)' % (diff[0], ys[diff[0]], got[diff[0] + 1])) if diff else ''))
        bad += len(diff)
    sys.exit(1 if bad else 0)
