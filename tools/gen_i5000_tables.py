#!/usr/bin/env python3
# Writes rtl/rabbit_i5000_tables.svh: MAME 0.289's I5000 volume table (i5000snd_device::device_start) and the OKI ADPCM step sizes
# (oki_adpcm_state::compute_tables).   python3 tools/gen_i5000_tables.py
import math, os
here = os.path.dirname(os.path.abspath(__file__))
vol, v = [], 2047.0
for i in range(256):
    vol.append(int(v + 0.5)); v /= 1.032
vol[255] = 0
steps = [int(math.floor(16.0 * pow(11.0 / 10.0, s))) for s in range(49)]
with open(os.path.join(here, '..', 'rtl', 'rabbit_i5000_tables.svh'), 'w') as f:
    f.write("// Generated by tools/gen_i5000_tables.py from MAME 0.289's i5000snd_device::device_start (the volume table) and\n")
    f.write("// oki_adpcm_state::compute_tables (the step sizes: floor(16 * 1.1^step)).\n")
    f.write("function automatic logic [11:0] i5k_vol(input logic [7:0] i);\n    case (i)\n")
    for i, x in enumerate(vol): f.write("        8'd%d: i5k_vol = 12'd%d;\n" % (i, x))
    f.write("    endcase\nendfunction\n\n")
    f.write("function automatic logic [10:0] i5k_step(input logic [5:0] s);\n    case (s)\n")
    for i, x in enumerate(steps): f.write("        6'd%d: i5k_step = 11'd%d;\n" % (i, x))
    f.write("        default: i5k_step = 11'd%d;\n    endcase\nendfunction\n" % steps[48])
