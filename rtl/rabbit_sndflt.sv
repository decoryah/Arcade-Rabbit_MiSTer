//------------------------------------------------------------------------------
// The "Enhanced" sound's output filter (OSD Sound: Enhanced), at the I5000's sample rate (the game's 47,962 Hz), for each side: two
// 2-pole Butterworth high-passes at 150 Hz and a 2-pole Butterworth low-pass at 11 kHz. MAME's decoding leaves a large wander below
// 150 Hz (the decoder's drift, up to 42 dB above a real board's recording: rumble that eats headroom and muddies the bass) and hiss on
// top. The coefficients: tools/sndflt_ref.py, which is this module bit for bit.
//
// Direct form I biquads in fixed point: the signal with 8 fraction bits in 27 bits, the coefficients Q2.25 (27 bits), one 27 x 27
// product a clock into a 57-bit sum, rounded back. The cascade shares the histories: a section's input history is the output history
// of the section before it. One multiplier serves both sides in turn (30 products a sample, about 100 clocks of the 2,000 there are).
//------------------------------------------------------------------------------
`default_nettype none

module rabbit_sndflt (
    input  logic               clk,
    input  logic               reset,
    input  logic               stb,             // a new sample on in_l / in_r
    input  logic signed [16:0] in_l,
    input  logic signed [16:0] in_r,
    output logic signed [15:0] out_l,
    output logic signed [15:0] out_r
);
    localparam int NSEC = 3;

    // generated by tools/sndflt_ref.py --sv: b0, b1, b2, -a1, -a2 of each section, Q2.25
    function automatic logic signed [26:0] coef(input logic [3:0] k, input logic [2:0] m);
        case ({k, m})
            {4'd0, 3'd0}: return 27'sd33091413;
            {4'd0, 3'd1}: return -27'sd66182826;
            {4'd0, 3'd2}: return 27'sd33091413;
            {4'd0, 3'd3}: return 27'sd66176437;
            {4'd0, 3'd4}: return -27'sd32634784;
            {4'd1, 3'd0}: return 27'sd33091413;
            {4'd1, 3'd1}: return -27'sd66182826;
            {4'd1, 3'd2}: return 27'sd33091413;
            {4'd1, 3'd3}: return 27'sd66176437;
            {4'd1, 3'd4}: return -27'sd32634784;
            {4'd2, 3'd0}: return 27'sd8586191;
            {4'd2, 3'd1}: return 27'sd17172382;
            {4'd2, 3'd2}: return 27'sd8586191;
            {4'd2, 3'd3}: return 27'sd5104046;
            {4'd2, 3'd4}: return -27'sd5894377;
            default: return 27'sd0;
        endcase
    endfunction

    // the histories: h[side][level][age], level 0 the input, 1..NSEC the sections' outputs; age 0 = n-1, 1 = n-2
    logic signed [26:0] h [2][NSEC + 1][2];
    logic signed [26:0] yk [NSEC];              // this sample's section outputs
    logic signed [26:0] xin [2];
    logic signed [26:0] cur;                    // the section's input this sample
    logic        side;
    logic  [3:0] k;
    logic  [2:0] m;
    logic  [1:0] drain;
    logic signed [26:0] opa, opb;
    logic signed [53:0] prod;
    logic signed [56:0] acc;
    logic        v1, v2;
    typedef enum logic [1:0] { S_IDLE, S_MAC, S_WAIT, S_UPD } st_t;
    st_t         st;

    logic signed [56:0] rnd;
    logic signed [31:0] ynew;
    always_comb begin
        rnd  = (acc + 57'sd16777216) >>> 25;
        ynew = (rnd > 57'sd67108863) ? 32'sd67108863 : (rnd < -57'sd67108864) ? -32'sd67108864 : rnd[31:0];
    end
    function automatic logic signed [15:0] sat16(input logic signed [26:0] v);
        logic signed [26:0] s;
        s = v >>> 8;
        if (s > 27'sd32767) return 16'sd32767;
        if (s < -27'sd32768) return -16'sd32768;
        return s[15:0];
    endfunction

    always_ff @(posedge clk) begin
        // the multiplier's pipeline: operands, product, sum
        prod <= opa * opb;
        v2   <= v1;
        if (v2) acc <= acc + 57'(prod);
        v1 <= 1'b0;
        if (reset) begin
            st <= S_IDLE; v1 <= 1'b0; v2 <= 1'b0; out_l <= '0; out_r <= '0;
            for (int s = 0; s < 2; s++) for (int l = 0; l <= NSEC; l++) begin h[s][l][0] <= '0; h[s][l][1] <= '0; end
        end else case (st)
            S_IDLE: if (stb) begin
                xin[0] <= 27'(in_l) <<< 8; xin[1] <= 27'(in_r) <<< 8;
                cur <= 27'(in_l) <<< 8;
                side <= 1'b0; k <= 4'd0; m <= 3'd0; acc <= '0; st <= S_MAC;
            end
            S_MAC: begin
                opa <= coef(k, m);
                case (m)
                    3'd0: opb <= cur;
                    3'd1: opb <= h[side][k][0];
                    3'd2: opb <= h[side][k][1];
                    3'd3: opb <= h[side][k + 4'd1][0];
                    default: opb <= h[side][k + 4'd1][1];
                endcase
                v1 <= 1'b1;
                if (m == 3'd4) begin drain <= 2'd0; st <= S_WAIT; end
                else m <= m + 3'd1;
            end
            S_WAIT: begin
                // the last product lands in acc two clocks after it is issued
                if (drain == 2'd2) begin
                    yk[k[2:0]] <= ynew[26:0]; cur <= ynew[26:0];
                    acc <= '0; m <= 3'd0;
                    if (k == 4'(NSEC - 1)) st <= S_UPD;
                    else begin k <= k + 4'd1; st <= S_MAC; end
                end else drain <= drain + 2'd1;
            end
            default: begin   // S_UPD: this side's histories, its output; then the other side
                h[side][0][1] <= h[side][0][0]; h[side][0][0] <= xin[side];
                for (int l = 1; l <= NSEC; l++) begin h[side][l][1] <= h[side][l][0]; h[side][l][0] <= yk[l - 1]; end
                if (!side) out_l <= sat16(yk[NSEC - 1]); else out_r <= sat16(yk[NSEC - 1]);
                if (!side) begin side <= 1'b1; k <= 4'd0; m <= 3'd0; acc <= '0; cur <= xin[1]; st <= S_MAC; end
                else st <= S_IDLE;
            end
        endcase
    end
endmodule
`default_nettype wire
